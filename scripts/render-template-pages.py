"""
Renders every page of every briefing / height-ban PDF template (including company overrides under
public/briefing-templates/overrides/<company>/) to WebP, so the app shows the document inside an
in-app viewer. An installed web app on iPhone cannot return from a PDF opened in a new tab, and
Safari shows only the first page of a PDF inside an iframe (field report, 2026-11-19).

Run again whenever a template PDF is added or changed:
    python -I scripts/render-template-pages.py
For /x/y/<lang>.pdf it writes /x/y/pages/<lang>-<n>.webp, and lib/documents/template-pages.ts.
A unit test (lib/documents/__tests__/template-viewer.test.ts) fails if they are out of date.
"""
import glob
import os
import sys

import fitz  # PyMuPDF
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, "public")
WIDTH = 1100  # px — sharp on phones, small enough to load quickly

pdfs = []
for kind in ("briefing-templates", "height-ban-templates"):
    pdfs += glob.glob(os.path.join(PUBLIC, kind, "**", "*.pdf"), recursive=True)

counts = {}
cleaned = set()
for pdf in sorted(pdfs):
    folder = os.path.dirname(pdf)
    out_dir = os.path.join(folder, "pages")
    os.makedirs(out_dir, exist_ok=True)
    if out_dir not in cleaned:
        for old in glob.glob(os.path.join(out_dir, "*.webp")):
            os.remove(old)
        cleaned.add(out_dir)
    lang = os.path.splitext(os.path.basename(pdf))[0]
    doc = fitz.open(pdf)
    for i, page in enumerate(doc, start=1):
        zoom = WIDTH / page.rect.width
        pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
        img = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
        img.save(os.path.join(out_dir, f"{lang}-{i}.webp"), "WEBP", quality=82, method=6)
    url = "/" + os.path.relpath(pdf, PUBLIC).replace(os.sep, "/")
    counts[url] = len(doc)
    print(url, len(doc), file=sys.stderr)

lines = [
    "// Generated by scripts/render-template-pages.py — do not edit by hand.",
    "// PDF template path → page count; page images live next to it: <folder>/pages/<language>-<n>.webp",
    "export const TEMPLATE_PAGE_COUNTS: Readonly<Record<string, number>> = {",
]
for url, n in counts.items():
    lines.append(f"  '{url}': {n},")
lines.append("};")
lines.append("")
with open(os.path.join(ROOT, "lib", "documents", "template-pages.ts"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
