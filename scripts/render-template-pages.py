"""
Renders every page of the briefing / height-ban PDF templates to a WebP image, so the app can
show the document inside an in-app viewer (an installed web app on iPhone cannot return from a
PDF opened in a new tab, and Safari shows only the first page of a PDF inside an iframe).

Run again whenever a template PDF changes:
    python -I scripts/render-template-pages.py
Writes public/<kind>-templates/pages/<language>-<n>.webp and lib/documents/template-pages.ts.
A unit test (lib/documents/__tests__/template-pages.test.ts) fails if they are out of date.
"""
import glob
import os
import sys

import fitz  # PyMuPDF
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIDTH = 1100  # px — sharp on phones, small enough to load quickly

counts = {}
for kind in ("briefing", "height-ban"):
    src_dir = os.path.join(ROOT, "public", f"{kind}-templates")
    out_dir = os.path.join(src_dir, "pages")
    os.makedirs(out_dir, exist_ok=True)
    for old in glob.glob(os.path.join(out_dir, "*.webp")):
        os.remove(old)
    counts[kind] = {}
    for pdf in sorted(glob.glob(os.path.join(src_dir, "*.pdf"))):
        lang = os.path.splitext(os.path.basename(pdf))[0]
        doc = fitz.open(pdf)
        for i, page in enumerate(doc, start=1):
            zoom = WIDTH / page.rect.width
            pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
            img = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
            img.save(os.path.join(out_dir, f"{lang}-{i}.webp"), "WEBP", quality=82, method=6)
        counts[kind][lang] = len(doc)
        print(kind, lang, len(doc), file=sys.stderr)

lines = [
    "// Generated by scripts/render-template-pages.py — do not edit by hand.",
    "// Page counts of the PDF templates; images live in public/<kind>-templates/pages/<language>-<n>.webp",
    "export const TEMPLATE_PAGE_COUNTS = {",
]
for kind, langs in counts.items():
    inner = ", ".join(f"{lang}: {n}" for lang, n in langs.items())
    lines.append(f"  '{kind}': {{ {inner} }},")
lines.append("} as const;")
lines.append("")
lines.append("export type TemplateKind = keyof typeof TEMPLATE_PAGE_COUNTS;")
lines.append("")
with open(os.path.join(ROOT, "lib", "documents", "template-pages.ts"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
